fn row(header: &Header, language: Language) -> ReferenceRow {
    use keys::tools::http_headers as words;
    let tr = |key| i18n::translate(language, key, &[]);
    let lower = header.name.to_lowercase();
    let does = word(
        language,
        &format!("tools.http-headers.words.headers.{lower}"),
    );
    let heading = word(
        language,
        &format!("tools.http-headers.groups.{}", header.group),
    );
    let direction = word(
        language,
        &format!("tools.http-headers.directions.{}", header.direction),
    );
    let tags: Vec<String> = [
        header.security.then(|| tr(words::SECURITY)),
        header.deprecated.then(|| tr(words::DEPRECATED)),
    ]
    .into_iter()
    .flatten()
    .collect();
    let mut name = Cell::mono(header.name);
    if !tags.is_empty() {
        name = name.below(tags.join(" · "));
    }
    let cells = vec![
        name,
        Cell::text(direction),
        Cell::text(does.clone()).below(header.example),
        Cell::text(header.by),
    ];
    ReferenceRow::new(header.name, header.group, cells)
        .searched_by([header.name, &does, header.example, header.by, &heading])
        .found_as(header.name, does)
}

pub(crate) fn table(language: Language) -> Table {
    Table {
        rows: HEADERS.iter().map(|it| row(it, language)).collect(),
        groups: groups_of(language, "tools.http-headers.groups", &GROUPS),
        columns: columns_of(
            language,
            "tools.http-headers.columns",
            &[
                ("name", Some(0.31)),
                ("direction", Some(0.11)),
                ("does", None),
                ("by", Some(0.16)),
            ],
        ),
        caption: keys::tools::http_headers::NAME,
        placeholder: keys::tools::http_headers::PLACEHOLDER,
        card_width: WIDE_CARD,
        matches: None,
    }
}

pub(super) fn make() -> Box<dyn Tool> {
    Reference::of(table)
}
